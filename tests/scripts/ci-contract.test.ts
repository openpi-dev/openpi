import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { parse } from "yaml";

interface Job {
  if?: string;
  needs?: string[];
  strategy?: { matrix: Record<string, unknown[]> };
  steps: {
    name?: string;
    if?: string;
    run?: string;
    env?: Record<string, string>;
  }[];
}

const { jobs } = parse(readFileSync(".github/workflows/ci.yml", "utf8")) as {
  jobs: Record<string, Job>;
};
const versions = ["22.19.0", 24, 26];

test("one canonical check retains every Node runtime and UI compatibility lane", () => {
  const runtime = jobs["test-node"]!;
  const ui = jobs["test-ui"]!;
  for (const version of versions) {
    assert.ok(runtime.strategy?.matrix["node-version"]?.includes(version));
    assert.ok(ui.strategy?.matrix["node-version"]?.includes(version));
  }
  assert.ok(
    ui.strategy?.matrix.include?.some((entry) => {
      const lane = entry as { os?: string; "node-version"?: string };
      return lane.os === "windows-latest" && lane["node-version"] === "22.19.0";
    }),
  );
  assert.ok(
    runtime.steps.some(
      (step) => step.run === "bun run test node" && step.if === undefined,
    ),
  );
  assert.ok(
    ui.steps.some(
      (step) => step.run === "bun run test ui" && step.if === undefined,
    ),
  );
  const check = runtime.steps.find((step) => step.run === "bun run check");
  const assets = runtime.steps.find(
    (step) => step.name === "Verify committed Web build",
  );
  assert.equal(check?.if, "matrix.node-version == '22.19.0'");
  assert.equal(assets?.if, check?.if);
});

test("the canonical asset check rejects stale, missing and untracked release files", {
  skip: process.platform === "win32",
}, () => {
  const command = jobs["test-node"]!.steps.find(
    (step) => step.name === "Verify committed Web build",
  )?.run;
  assert.ok(command);
  const cwd = mkdtempSync(join(tmpdir(), "openpi-ci-assets-"));
  const file = join(cwd, "web/dist/app.js");
  const run = () =>
    spawnSync("bash", ["-e", "-c", command], { cwd, encoding: "utf8" });
  const git = (...args: string[]) =>
    execFileSync("git", args, { cwd, stdio: "pipe" });
  try {
    mkdirSync(join(cwd, "web/dist"), { recursive: true });
    writeFileSync(file, "committed release bytes\n");
    git("init", "-q");
    git("config", "core.fsmonitor", "false");
    git("config", "core.untrackedCache", "false");
    git("add", "web/dist/app.js");
    git(
      "-c",
      "commit.gpgsign=false",
      "-c",
      "core.hooksPath=/dev/null",
      "-c",
      "user.name=CI fixture",
      "-c",
      "user.email=ci@example.invalid",
      "commit",
      "-qm",
      "release fixture",
    );
    assert.equal(run().status, 0);
    writeFileSync(file, "stale generated bytes\n");
    assert.notEqual(run().status, 0);
    writeFileSync(file, "committed release bytes\n");
    const extra = join(cwd, "web/dist/untracked.js");
    writeFileSync(extra, "untracked output\n");
    assert.notEqual(run().status, 0);
    rmSync(extra);
    rmSync(file);
    assert.notEqual(run().status, 0);
    writeFileSync(file, "committed release bytes\n");
    assert.equal(run().status, 0);
    rmSync(join(cwd, ".git"), { recursive: true });
    assert.notEqual(
      run().status,
      0,
      "Git errors must not be treated as clean assets",
    );
  } finally {
    rmSync(cwd, { recursive: true, force: true });
  }
});

test("the E2E matrix covers every native shard and keeps the provider handoff", () => {
  const e2e = jobs["web-e2e-shards"]!;
  const command =
    e2e.steps.find((step) => step.run?.includes("--shard="))?.run ?? "";
  const total = Number(
    /--shard=\$\{\{ matrix\.shard \}\}\/(\d+)/u.exec(command)?.[1],
  );
  assert.ok(Number.isSafeInteger(total) && total > 0);
  assert.deepEqual(
    e2e.strategy?.matrix.shard,
    Array.from({ length: total }, (_, index) => index + 1),
  );
  assert.match(
    command,
    /playwright test --config tests\/web\/playwright\.config\.ts/u,
  );
  assert.ok(
    e2e.steps.some(
      (step) =>
        step.if === "matrix.shard == 1" &&
        step.run?.includes("playwright.plan-provider.config.ts"),
    ),
  );
});

test("required gates reject failed, cancelled, skipped and missing dependencies", {
  // These are Ubuntu job scripts; Windows still checks matrix and shard coverage.
  skip: process.platform === "win32",
}, () => {
  for (const id of ["test", "windows-background-terminals", "web-e2e"]) {
    const gate = jobs[id]!;
    assert.equal(gate.if, "always()");
    const step = gate.steps.find((entry) => entry.run);
    assert.ok(step?.run && step.env);
    const bindings = Object.entries(step.env).map(([key, expression]) => {
      const dependency = /^\$\{\{ needs\.([\w-]+)\.result \}\}$/u.exec(
        expression,
      )?.[1];
      assert.ok(dependency && gate.needs?.includes(dependency));
      return [key, dependency] as const;
    });
    assert.deepEqual(
      bindings.map(([, dependency]) => dependency).sort(),
      [...gate.needs!].sort(),
    );
    const env = Object.fromEntries(bindings.map(([key]) => [key, "success"]));
    const run = (values: Record<string, string>) =>
      spawnSync("bash", ["-e", "-c", step.run!], {
        env: { ...process.env, ...values },
      }).status;
    assert.equal(run(env), 0, `${id} accepts complete success`);
    for (const [key, dependency] of bindings) {
      for (const result of ["failure", "cancelled", "skipped", ""]) {
        assert.notEqual(
          run({ ...env, [key]: result }),
          0,
          `${id} rejects ${dependency}: ${result}`,
        );
      }
    }
  }
  // Testing committed assets is safe only if the browser gate also requires
  // the canonical rebuild/consistency check, not just the browser shards.
  assert.ok(jobs["web-e2e"]!.needs?.includes("test-node"));
});
